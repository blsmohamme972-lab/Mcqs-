package com.mcqs.app.srs

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.double
import kotlinx.serialization.json.doubleOrNull
import kotlinx.serialization.json.int
import kotlinx.serialization.json.intOrNull
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import kotlin.random.Random

/** Replays review sequences generated by py-fsrs 6.3.2 (tools/gen_fsrs_vectors.py). */
class FsrsTest {
    private val root = Json.parseToJsonElement(
        javaClass.classLoader!!.getResource("fsrs_vectors.json")!!.readText()
    ).jsonObject

    private fun scheduler(cfg: JsonObject) = Scheduler(
        w = cfg["parameters"]!!.jsonArray.map { it.jsonPrimitive.double }.toDoubleArray(),
        desiredRetention = cfg["desired_retention"]!!.jsonPrimitive.double,
        learningSteps = cfg["learning_steps"]!!.jsonArray.map { it.jsonPrimitive.long * 1000 },
        relearningSteps = cfg["relearning_steps"]!!.jsonArray.map { it.jsonPrimitive.long * 1000 },
        maximumInterval = cfg["maximum_interval"]!!.jsonPrimitive.int,
        enableFuzzing = cfg["enable_fuzzing"]!!.jsonPrimitive.boolean,
    )

    @Test
    fun matchesPyFsrs() {
        val schedulers = root["configs"]!!.jsonArray.map { scheduler(it.jsonObject) }
        var reviews = 0
        for ((ci, case) in root["cases"]!!.jsonArray.withIndex()) {
            val c = case.jsonObject
            val sch = schedulers[c["config"]!!.jsonPrimitive.int]
            var card = SrsCard(due = 0L)
            for ((si, stepEl) in c["steps"]!!.jsonArray.withIndex()) {
                val e = stepEl.jsonObject
                val where = "case $ci step $si"
                card = sch.review(card, Rating.of(e["rating"]!!.jsonPrimitive.int), e["t"]!!.jsonPrimitive.long)
                assertEquals(where, e["state"]!!.jsonPrimitive.int, card.state.code)
                assertEquals(where, e["step"]!!.jsonPrimitive.intOrNull, card.step)
                assertEquals(where, e["stability"]!!.jsonPrimitive.doubleOrNull!!, card.stability!!, 1e-9)
                assertEquals(where, e["difficulty"]!!.jsonPrimitive.doubleOrNull!!, card.difficulty!!, 1e-9)
                assertEquals(where, e["due"]!!.jsonPrimitive.long, card.due)
                reviews++
            }
        }
        assertTrue(reviews > 1000)
    }

    /** Exact fuzzed-interval ranges observed from py-fsrs (40k samples each), including its +1 rounding edge. */
    @Test
    fun fuzzMatchesPyFsrsRanges() {
        val sch = Scheduler(random = Random(7))
        val expected = mapOf(2L to 2L..2L, 3L to 2L..5L, 7L to 5L..10L, 11L to 9L..14L, 40L to 36L..45L, 200L to 188L..213L)
        for ((days, range) in expected) {
            val seen = (1..40_000).map { sch.fuzz(days * DAY_MS) / DAY_MS }.toSortedSet()
            assertEquals("interval $days", range.toList(), seen.toList())
        }
    }
}
